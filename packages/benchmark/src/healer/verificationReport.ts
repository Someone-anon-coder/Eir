import type { AuditEvidence, FixmeEvidence } from "./evidenceCli.js";
import type { ReportMeta } from "./report.js";
import type { RunRecord } from "./runRecord.js";
import type { RowEvidence } from "./transcriptEvidence.js";
import type { TraceCheckEntry } from "./traceCheckCli.js";
import {
  compareReruns,
  formatTally,
  summarizeFalseHeals,
  type FalseHealSummary,
  type TargetVerification,
} from "./verification.js";

export interface ClassShuffleStrict {
  readonly replayed: number;
  /** The element Playwright resolved was the target container itself. */
  readonly resolvedIsTarget: number;
  /** It resolved to something else (a descendant heading or an outer ancestor) and was credited only by ancestor path. */
  readonly resolvedIsOther: number;
  readonly others: readonly {
    readonly targetId: string;
    readonly run: number;
    readonly resolved: string;
  }[];
}

export interface TranscriptRow {
  readonly runClass: string;
  readonly targetId: string;
  readonly run: number;
  readonly firstActiveTableEvidence: RowEvidence;
  readonly healerClaim: string | undefined;
}

export interface DestructiveExperiment {
  readonly build: string;
  readonly results: readonly {
    readonly owner: string;
    readonly freshLoadActiveRows: number;
    readonly actionButtonOrder: string;
    readonly afterOriginalFirstClickActiveRows: number;
    readonly archivedRowsWithOwner: number;
    readonly afterReloadActiveRows: number;
  }[];
}

export interface VerificationInput {
  readonly meta: ReportMeta;
  readonly original: readonly RunRecord[];
  readonly rerun: readonly RunRecord[];
  readonly anchored: readonly RunRecord[];
  readonly traceFalseHeals: readonly TraceCheckEntry[];
  readonly traceControl: readonly TraceCheckEntry[];
  readonly classShuffleStrict: ClassShuffleStrict;
  readonly audit: readonly AuditEvidence[];
  readonly fixme: readonly FixmeEvidence[];
  readonly transcripts: readonly TranscriptRow[];
  readonly experiment: DestructiveExperiment | undefined;
  readonly versionCheck: Readonly<Record<string, string>>;
}

export interface VerificationReport extends VerificationInput {
  readonly targets: readonly TargetVerification[];
  readonly falseHeals: FalseHealSummary;
  readonly spendUsd: { readonly rerun: number; readonly anchored: number };
}

const sumCost = (rs: readonly RunRecord[]): number =>
  rs.reduce((a, r) => a + (r.healer?.costUsd ?? 0), 0);

export function buildVerificationReport(input: VerificationInput): VerificationReport {
  const targets = compareReruns(input.original, input.rerun, input.anchored);
  return {
    ...input,
    targets,
    falseHeals: summarizeFalseHeals(targets),
    spendUsd: { rerun: sumCost(input.rerun), anchored: sumCost(input.anchored) },
  };
}

const cell = (t: string): string => t.replace(/\|/g, "\\|").replace(/\n/g, " ");
const usd = (n: number): string => `$${n.toFixed(4)}`;
const rate = (n: number, d: number): string =>
  d === 0 ? "n/a" : `${((100 * n) / d).toFixed(1)}% (${n}/${d})`;

export function renderFixmeAppendix(fixme: readonly FixmeEvidence[]): string[] {
  const rows = [
    "Every `fixme`d healer run: the comment lines and `test.fixme` marker exactly as written in the final spec, next to the bug that was injected. No judgement is made here about whether a comment names the real cause.",
    "",
    "| Class run | Target | Run | Injected bug (source) | Comment lines in the final spec, verbatim |",
    "| --- | --- | ---: | --- | --- |",
  ];
  for (const f of fixme) {
    rows.push(
      `| ${f.runClass} | ${cell(f.targetId)} | ${f.run} | ${cell(f.injectedBug)} (${cell(f.injectedBugSource)}) | ${f.commentLines.map((l) => `\`${cell(l)}\``).join("<br>")} |`,
    );
  }
  return rows;
}

export function renderVerificationMarkdown(r: VerificationReport): string {
  const m = r.meta;
  const fh = r.falseHeals;
  const out: string[] = [
    "# Healer comparison: verification pass",
    "",
    "Generated by `pnpm --filter benchmark bench:healer-verification` from the verification dataset and the saved evidence. Do not edit by hand. The original 276-run dataset is the primary result and is reported in `healer-comparison.{json,md}`; **nothing here replaces it**. Reruns are a separate dataset (`verification`), and anchored-variant runs a third (`verification-anchored`).",
    "",
    "| | |",
    "| --- | --- |",
    `| Generated | ${m.generatedAt} |`,
    `| Playwright | ${m.playwrightVersion} |`,
    `| Claude Code CLI | ${m.claudeCodeVersions.join(", ")} |`,
    `| Model IDs seen in the reruns | ${m.modelIds.join(", ")} |`,
    `| Healer agent file SHA-256 | \`${m.healerAgentSha256}\` |`,
    `| Seed | ${m.seed} |`,
    `| Reruns per target | 5 healer + 1 Eir (anchored variant: the same) |`,
    `| CLI-reported spend | reruns ${usd(r.spendUsd.rerun)}, anchored ${usd(r.spendUsd.anchored)} (cap $5 total) |`,
    ...Object.entries(r.versionCheck).map(([k, v]) => `| Version check: ${k} | ${v} |`),
    "",
    "## 1. Rerun results next to the originals",
    "",
    `False-heal runs over the compared targets: **original ${rate(fh.originalWrong, fh.originalRuns)}**, **rerun ${rate(fh.rerunWrong, fh.rerunRuns)}**, anchored variant ${rate(fh.anchoredWrong, fh.anchoredRuns)} (the anchored runs cover only the position-only targets, so they are not comparable to the other two as a whole).`,
    "",
    "| Class run | Target | Original healer (3 runs) | Rerun healer (5 runs) | Anchored variant healer (5 runs) | Eir original | Eir rerun | Eir reproduces | Eir anchored |",
    "| --- | --- | --- | --- | --- | --- | --- | :---: | --- |",
    ...r.targets.map(
      (t) =>
        `| ${t.runClass} | ${cell(t.targetId)} | ${formatTally(t.original)} | ${formatTally(t.rerun)} | ${formatTally(t.anchored)} | ${t.eirOriginal ?? "n/a"} | ${t.eirRerun ?? "n/a"} | ${t.eirReproduces === undefined ? "n/a" : t.eirReproduces ? "yes" : "NO"} | ${t.eirAnchored ?? "n/a"} |`,
    ),
    "",
    "## 2. Judge cross-check from the trace (not the collector)",
    "",
    `Each final spec was replayed against the marked build with Playwright tracing on; the acted-on element is read from the trace's own record of the action target. **${r.traceFalseHeals.filter((e) => e.agreement.agree).length} of ${r.traceFalseHeals.length} false heals agree with the collector** (all replays green).`,
    "",
    "| Class run | Target | Run | Interaction (trace) | Element hit (trace) | Collector | Agree |",
    "| --- | --- | ---: | --- | --- | --- | :---: |",
    ...r.traceFalseHeals.map(
      (e) =>
        `| ${e.runClass} | ${cell(e.targetId)} | ${e.run} | ${e.traced.map((a) => `${a.method} → ${a.tag}`).join("; ")} | ${e.agreement.traceSet.join(", ")} | ${e.collectorActedOn.join(", ")} | ${e.agreement.agree ? "yes" : "NO"} |`,
    ),
    "",
    `**Negative control.** The same check over the ${r.traceControl.length} \`healed-correct\` runs: ${r.traceControl.filter((e) => e.agreement.agree).length} agree, ${r.traceControl.filter((e) => !e.agreement.agree).length} disagree, and every replay was green. No disagreement involves a target, decoy or other element key. All of them are container-marker keys, in two groups:`,
    "",
    ...r.traceControl
      .filter((e) => !e.agreement.agree)
      .map(
        (e) =>
          `- ${e.runClass} \`${e.targetId}\` run ${e.run}: trace only [${e.agreement.onlyInTrace.join(", ")}], collector only [${e.agreement.onlyInCollector.join(", ")}]`,
      ),
    "",
    "The near-duplicate group is a build-version difference: those runs were judged on a marked build from before container markers existed, so the collector could not record `devices.active.table`. The class-shuffle group is the path-attribution leniency described next.",
    "",
    "### Class-shuffle: path attribution versus the element Playwright resolved",
    "",
    `Of the ${r.classShuffleStrict.replayed} class-shuffle runs the judge counted \`healed-correct\` (attributed by marked-ancestor path), **${r.classShuffleStrict.resolvedIsTarget}** resolved the target container itself and **${r.classShuffleStrict.resolvedIsOther}** resolved a different element and were credited only because the click's ancestor path included the target. This is reported beside the original figure, not instead of it.`,
    "",
    "| Target | Run | Playwright resolved |",
    "| --- | ---: | --- |",
    ...r.classShuffleStrict.others.map((o) => `| ${o.targetId} | ${o.run} | ${o.resolved} |`),
    "",
    "## 3. Spec-intent audit of the 14 false heals",
    "",
    "`position only` = the original action picks its row by `nth-child` with no row text. The anchor columns say where text the healer anchored on came from: in the original spec as test data, in the page's data, or both. `Receiver changed` = the healer changed the expression an assertion is evaluated on, which is the documented blind spot of the assertion diff.",
    "",
    "| Class run | Target | Run | Original action identifies row by | Anchor text (in spec / in page data) | Receiver changed | Ground-truth element | Element hit |",
    "| --- | --- | ---: | --- | --- | :---: | --- | --- |",
    ...r.audit.map(
      (a) =>
        `| ${a.runClass} | ${cell(a.targetId)} | ${a.run} | ${a.originalActionIdentity} | ${a.anchors.length === 0 ? "(none extracted)" : a.anchors.map((x) => `${cell(x.text)} (${x.inOriginalSpec ? "spec" : "not in spec"} / ${x.inPageData ? "page" : "not in page"})`).join("; ")} | ${a.receiver.changed ? "yes" : "no"} | ${a.groundTruthElement} | ${a.actedOn.join(", ")} |`,
    ),
    "",
    "## 4. Destructive-debugging hypothesis",
    "",
    "Direct experiment on the mutated `sibling-reorder` build, replaying the original spec's first action:",
    "",
    "| Owner | Active rows on fresh load | Action buttons in order | Active rows after the original first click | Same owner in the archived table | Active rows after `reload()` |",
    "| --- | ---: | --- | ---: | ---: | ---: |",
    ...(r.experiment?.results ?? []).map(
      (e) =>
        `| ${e.owner} | ${e.freshLoadActiveRows} | ${e.actionButtonOrder} | ${e.afterOriginalFirstClickActiveRows} | ${e.archivedRowsWithOwner} | ${e.afterReloadActiveRows} |`,
    ),
    "",
    "What the healer's first page evidence showed, for the 7 `actionsOrder` false heals (is the intended row in the Active table?):",
    "",
    "| Class run | Target | Run | First Active-table evidence | What the healer said about the archived table |",
    "| --- | --- | ---: | --- | --- |",
    ...r.transcripts.map(
      (t) =>
        `| ${t.runClass} | ${cell(t.targetId)} | ${t.run} | ${t.firstActiveTableEvidence} | ${cell(t.healerClaim ?? "")} |`,
    ),
    "",
    "## Appendix: all `fixme` comments",
    "",
    ...renderFixmeAppendix(r.fixme),
    "",
  ];
  return out.join("\n");
}
